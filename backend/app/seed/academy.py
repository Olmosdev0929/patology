        yield meta, [
            {"chapter": ch, "en": en, "uz": uz, "ru": ru, "terms": [{"term": a, "uz": x, "ru": y} for a, x, y in terms]}
            for ch, en, uz, ru, terms in b["sentences"]
        ]


